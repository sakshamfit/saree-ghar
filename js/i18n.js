/* containers crossfaded during a live switch */
const FADE_GROUPS = ['#mainNav', '.hero-copy', '.hero-scroll', '.na-intro', '.na-ethos', '.na-statement', '.na-grid', '.or-head', '.or-side', '.or-wall', '.or-foot', '.sc-intro', '.sc-side', '.sc-rail', '.sc-foot', '.bs-intro', '.bs-side', '.bs-rail', '.ch-copy', '.ci-info', '.ci-form', '.ci-quote', '.cl-center', '.cl-map'];

let current = 'en';
let swapping = false;

export function getLang() { return current; }

/* plain-string lookup in the live language (falls back to English) */
export function t(key) {
  return (STRINGS[current] && STRINGS[current][key]) ?? STRINGS.en[key] ?? '';
}

function readStored() {
  try { return localStorage.getItem('siaara-lang'); } catch { return null; }
}

function store(lang) {
  try { localStorage.setItem('siaara-lang', lang); } catch { /* private mode */ }
}

function applyStrings(lang) {
  const dict = STRINGS[lang];
  document.documentElement.lang = lang;
  document.body.classList.toggle('lang-te', lang === 'te');

  for (const el of document.querySelectorAll('[data-i18n]')) {
    const v = dict[el.dataset.i18n];
    if (v != null) el.innerHTML = v;
  }
  for (const el of document.querySelectorAll('[data-i18n-aria]')) {
    const v = dict[el.dataset.i18nAria];
    if (v != null) el.setAttribute('aria-label', v);
  }
  for (const el of document.querySelectorAll('[data-i18n-ph]')) {
    const v = dict[el.dataset.i18nPh];
    if (v != null) el.setAttribute('placeholder', v);
  }
  for (const btn of document.querySelectorAll('.lang-btn')) {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', String(active));
  }
}

export function setLang(lang, animate = true) {
  if (!STRINGS[lang] || lang === current || swapping) return;
  current = lang;
  store(lang);

  if (!animate || typeof gsap === 'undefined') {
    applyStrings(lang);
    return;
  }

  /* only crossfade groups that are actually visible — pre-reveal sections
     must stay hidden until their own scroll choreography plays */
  const targets = FADE_GROUPS.filter((sel) => {
    const el = document.querySelector(sel);
    return el && parseFloat(gsap.getProperty(el, 'opacity')) > 0.5;
  });

  swapping = true;
  gsap.timeline()
    .to(targets, {
      autoAlpha: 0.12, duration: 0.22, ease: 'power2.in', stagger: 0.02,
    })
    .add(() => { applyStrings(lang); swapping = false; })
    .to(targets, {
      autoAlpha: 1, duration: 0.45, ease: 'power2.out', stagger: 0.03,
    }, '+=0.02');
}

export function initI18n() {
  const stored = readStored();
  if (stored && STRINGS[stored] && stored !== current) {
    current = stored;
  }
  applyStrings(current);

  for (const btn of document.querySelectorAll('.lang-btn')) {
    btn.addEventListener('click', () => setLang(btn.dataset.lang, true));
  }
}
